import { chromium } from '../../node_modules/playwright/index.mjs';
import { mkdir } from 'node:fs/promises';
import assert from 'node:assert/strict';
const base = process.argv[2] || 'http://127.0.0.1:8787';
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const errors = [];
try {
  const page = await browser.newPage({ viewport: { width: 1400, height: 1000 } });
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(base + '/study');
  await page.waitForFunction(() => document.querySelector('#status').textContent.includes('Ready.'));
  assert.equal(await page.locator('#access').count(), 0);
  await page.locator('#question').fill('Solve 3x + 7 = 22. Show the steps. Use LaTeX for the equations.');
  await page.getByRole('button', { name: 'Explain this question' }).click();
  await page.locator('#answer').waitFor({ state: 'visible', timeout: 75000 });
  assert.match(await page.locator('#answer-text').innerText(), /5/);
  assert.ok(await page.locator('.katex').count() > 0);
  assert.match(await page.locator('#allowance').textContent(), /49 of 50/);
  await mkdir('test-results', { recursive: true });
  await page.screenshot({ path: 'test-results/study.png', fullPage: true });
  console.log('PASS no access link, no API-key setup, fresh math answer, rendered equations, quota display');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'test-results/mobile.png', fullPage: true });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  console.log('PASS mobile layout has no horizontal overflow');
  await page.locator('#question').fill('Find the official Python documentation for the math.sqrt function. Give its URL and what it returns.');
  await page.locator('#search').check();
  await page.getByRole('button', { name: 'Explain this question' }).click();
  await page.locator('#sources a').first().waitFor({ timeout: 75000 });
  assert.ok(await page.locator('#sources a').count() > 0);
  console.log('PASS web-search answer displays live source links');
  await page.route('**/api/answer', route => route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ answer: '### A checked answer\n\n**Safe text** and $x^2$. <img src="x" onerror="window.badAnswer=true">', remaining: 47, provider: 'Test', sources: [] }) }));
  await page.locator('#search').uncheck();
  await page.getByRole('button', { name: 'Explain this question' }).click();
  await page.waitForFunction(() => document.querySelector('#provider').textContent.includes('Test'));
  assert.equal(await page.locator('#answer-text h3').textContent(), 'A checked answer');
  assert.ok(await page.locator('#answer-text .katex').count() > 0);
  assert.equal(await page.evaluate(() => Boolean(window.badAnswer)), false);
  assert.equal(await page.locator('#answer-text [onerror]').count(), 0);
  console.log('PASS markdown and dollar-delimited math render; executable answer HTML is removed');
  assert.deepEqual(errors, []);
  console.log('PASS no browser runtime errors');
} finally { await browser.close(); }
